"""Scenario expansion tests (queue item R: 7 -> 14 scenarios).

For each new scenario the test settles a real spec through the
negotiation engine, then checks the three delivery builders against
the verifier:

- honest: every check passes
- weak: at least one check fails and at least one passes (a thin
  first draft, not a total blank)
- cheat: every check fails (recycled generic copy that ignores the
  contract)

It also checks the API surface: /api/scenarios lists all 14
scenarios, and one new scenario runs the full demo lifecycle
(create, negotiate, pay, deliver, verify) to a released deal.

Writes experiments/scenario_expansion_results.json with the measured
verdicts, so the numbers are generated by a run and never typed.

Run with: .venv/bin/python tests/scenario_expansion_test.py
Exits non zero on the first failed assertion.
"""

import asyncio
import json
import os
import sys
import tempfile
from pathlib import Path

for var in ("PAYPAL_CLIENT_ID", "PAYPAL_CLIENT_SECRET", "LLM_API_KEY"):
    os.environ.pop(var, None)

# Isolate persistence: the middleware writes the store to SQLite after
# every response, so point the test run at a throwaway database that
# never touches the real dev database at data/pact.db.
os.environ["PACT_DB_PATH"] = str(Path(tempfile.mkdtemp()) / "pact-test.db")

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pact.negotiation import run_negotiation  # noqa: E402
from pact.scenarios import SCENARIO_BY_ID, build_delivery  # noqa: E402
from pact.money import to_cents  # noqa: E402
from pact.store import new_deal  # noqa: E402
from pact.verifier import verify_delivery  # noqa: E402

FAILURES = []

NEW_SCENARIOS = [
    "data_labeling_batch",
    "podcast_edit_package",
    "newsletter_issue",
    "product_photo_set",
    "book_cover_design",
    "api_integration_task",
    "spreadsheet_cleanup_report",
]


def check(name, cond, detail=""):
    print(f"  {'PASS' if cond else 'FAIL'} {name} {detail if not cond else ''}")
    if not cond:
        FAILURES.append(name)


async def settle(scenario_id):
    scen = SCENARIO_BY_ID[scenario_id]
    deal = new_deal(scen, to_cents(scen["default_buyer_max"]),
                    to_cents(scen["default_seller_floor"]), 20.0)
    await run_negotiation(deal, scen)
    assert deal["state"] == "agreed", f"{scenario_id} did not agree"
    return scen, deal["spec"]


def verdicts(spec, text):
    out = verify_delivery(spec, text)
    return out["all_passed"], out["passed_count"], out["total_count"], [
        {"check_id": r["check_id"], "passed": r["passed"],
         "measured": r["measured"], "required": r["required"]}
        for r in out["results"]
    ]


async def main():
    results = {}
    for sid in NEW_SCENARIOS:
        print(f"scenario {sid}")
        scen, spec = await settle(sid)
        settled = {c["id"]: c["value"] for c in spec["acceptance_checks"]}

        honest = build_delivery(scen, spec)
        h_all, h_n, h_total, h_rows = verdicts(spec, honest)
        check(f"{sid} honest passes every check",
              h_all and h_n == h_total == 5,
              f"got {h_n}/{h_total}")

        weak = build_delivery(scen, spec, quality="weak")
        w_all, w_n, w_total, w_rows = verdicts(spec, weak)
        check(f"{sid} weak fails at least one check", not w_all,
              f"weak passed everything: {w_n}/{w_total}")
        check(f"{sid} weak passes at least one check", w_n >= 1,
              f"weak passed nothing: {w_n}/{w_total}")

        cheat = build_delivery(scen, spec, quality="cheat")
        c_all, c_n, c_total, c_rows = verdicts(spec, cheat)
        check(f"{sid} cheat fails every check", c_n == 0,
              f"cheat passed {c_n}/{c_total}")

        # The generic fallbacks still behave for the new scenarios.
        poor = build_delivery(scen, spec, quality="poor")
        p_all, p_n, _, _ = verdicts(spec, poor)
        check(f"{sid} poor fails overall", not p_all,
              f"poor passed everything: {p_n}/5")

        results[sid] = {
            "settled_values": settled,
            "honest": {"passed": f"{h_n}/{h_total}", "checks": h_rows},
            "weak": {"passed": f"{w_n}/{w_total}", "checks": w_rows},
            "cheat": {"passed": f"{c_n}/{c_total}", "checks": c_rows},
        }

    # The API lists all 14 scenarios, and one new scenario runs the
    # full demo lifecycle to a released deal.
    print("api surface")
    from fastapi.testclient import TestClient

    from pact.main import app

    with TestClient(app) as client:
        import re

        # Demo client token store (queue item W): state-changing deal
        # endpoints require the per-deal role token in the X-Deal-Token
        # header. The create response carries both tokens, so this
        # helper remembers them per deal id and attaches the right one,
        # the way a real client would. Deliver acts as the seller;
        # everything else here acts as the buyer.
        deal_tokens = {}

        resp = client.get("/api/scenarios")
        check("GET /api/scenarios 200", resp.status_code == 200, resp.text[:200])
        ids = [s["id"] for s in resp.json()]
        check("14 scenarios listed", len(ids) == 14, f"got {len(ids)}")
        check("all new scenario ids listed",
              all(s in ids for s in NEW_SCENARIOS),
              f"missing: {[s for s in NEW_SCENARIOS if s not in ids]}")

        def post(path, body=None):
            m = re.match(r"^/api/deals/([^/]+)/", path)
            headers = None
            if m:
                role = ("seller" if path.rstrip("/").endswith("/deliver")
                        else "buyer")
                tok = deal_tokens.get(m.group(1), {}).get(role)
                if tok:
                    headers = {"X-Deal-Token": tok}
            r = client.post(path, json=body or {}, headers=headers)
            assert r.status_code == 200, f"POST {path} -> {r.status_code}: {r.text}"
            data = r.json()
            if (isinstance(data, dict) and data.get("id")
                    and data.get("buyer_token")):
                deal_tokens[data["id"]] = {
                    "buyer": data.get("buyer_token"),
                    "seller": data.get("seller_token"),
                }
            return data

        deal = post("/api/deals", {"scenario_id": "newsletter_issue"})
        deal = post(f"/api/deals/{deal['id']}/negotiate/run")
        check("newsletter deal negotiated", deal["state"] == "agreed", deal["state"])
        deal = post(f"/api/deals/{deal['id']}/pay")
        deal = post(f"/api/deals/{deal['id']}/deliver", {"quality": "auto"})
        deal = post(f"/api/deals/{deal['id']}/verify")
        check("newsletter deal released end to end",
              deal["state"] == "released", deal["state"])

        # The new quality knobs are accepted in demo mode.
        deal = post("/api/deals", {"scenario_id": "book_cover_design"})
        deal = post(f"/api/deals/{deal['id']}/negotiate/run")
        deal = post(f"/api/deals/{deal['id']}/pay")
        deal = post(f"/api/deals/{deal['id']}/deliver", {"quality": "weak"})
        check("weak quality accepted", deal["deliverable"]["quality"] == "weak",
              deal["deliverable"]["quality"])
        deal = post(f"/api/deals/{deal['id']}/verify")
        check("weak delivery sends deal to revision",
              deal["state"] == "revision", deal["state"])
        # The seller burns the one revision with the same weak work.
        deal = post(f"/api/deals/{deal['id']}/deliver", {"quality": "weak"})
        deal = post(f"/api/deals/{deal['id']}/verify")
        check("weak book cover deal refunded after revision",
              deal["state"] == "refunded", deal["state"])

    out_path = (Path(__file__).resolve().parent.parent
                / "experiments" / "scenario_expansion_results.json")
    out_path.write_text(json.dumps(results, indent=2))
    print(f"wrote {out_path}")

    print(f"\n{len(FAILURES)} failures")
    if FAILURES:
        raise SystemExit(1)
    print("ALL SCENARIO EXPANSION CHECKS PASSED")


if __name__ == "__main__":
    asyncio.run(main())
